// Usb 定义/声明一个接口
type Usb interface {
	// Start 声明两个没有实现的方法
	Start()
	Stop()
}

type Usb2 interface {
	Start()
	Stop()
}

type Phone struct {
}

// Start 让Phone实现Usb接口的方法
// fixme 其实已经同时实现了usb和usb2这两个接口，这在别的语言中是做不到的
func (p *Phone) Start() {
	fmt.Println("手机开始工作")
}
func (p *Phone) Stop() {
	fmt.Println("手机停止工作")
}

type Camera struct {
}

// Start 让相机也实现这两个方法
// fixme 所谓的实现了一个接口，指的是实现了或者接口里的所有方法，比如这里usb里只有start和stop都实现了，就叫实现了usb接口
func (p *Camera) Start() {
	fmt.Println("相机开始工作")
}
func (p *Camera) Stop() {
	fmt.Println("相机停止工作")
}

type Computer struct {
}

// Work 方法接收的是Usb接口类型参数
// fixme 此时只要是实现了接口里的方法，实现了这个接口，都可以调用，这里无论是usb还是usb2
func (c *Computer) Work(usb Usb2) {
	// 通过接口去调用方法
	usb.Start()
	usb.Stop()
}

func main() {
	c := Computer{}
	phone := &Phone{}
	camera := &Camera{}
	// 可以看到这里使用接口时完全没有多余的声明和定义，这就得益于go接口的低耦合
	c.Work(phone)
	c.Work(camera) // fixme 整体感觉上非常的简明且码量少

}
