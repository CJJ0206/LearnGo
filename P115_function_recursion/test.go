package P115_function_recursion

import "fmt"

func Test1(n int) {
	if n > 2 {
		n--
		Test1(n) // Test(n-1)  Test(n-2)  Test(n-3) --> 最底层先输出
	}
	// n = 4 时，Test(4) -> Test(3) -> Test(2)  ---> n=2 时 if 会跳过，由于我们打印写在外面所以会继续打印
	// 输出的第一个2是最后不满足if时直接输出的，第二个2是3--后的2，最后输出3
	fmt.Println("n =", n)
}

func Test2(n int) {
	if n > 2 {
		n--
		Test2(n)
	} else {
		fmt.Println("n =", n) // 值输出一个 2
	}
}

/*
【 阶段一：递归深入 (入栈 / Push) 】
程序从左到右依次调用，每次调用都会在栈顶压入一个新的函数帧，并挂起当前层。

   (空)          1.第一层调用          2.第二层调用            3.第三层(最底层)调用
|          |    |                |    |                |     | 3. Test1(2)    | <--- 传入n=2。进不去if，直接准备打印
|          |    |                |    | 2. Test1(3)    |     +----------------+
|          | -> | 1. Test1(4)    | -> +----------------+  -> | 2. Test1(3)    | <--- 内存中的n已减为2 (挂起，等待上层结束)
+----------+    +----------------+    | 1. Test1(4)    |     +----------------+
   Main         传入n=4，执行n--变3      传入n=3，执行n--变2      | 1. Test1(4)    | <--- 内存中的n已减为3 (挂起，等待上层结束)
                调用Test1(3)，挂起       调用Test1(2)，挂起      +----------------+
                                                             (此时达到最大栈深)

-------------------------------------------------------------------------

【 阶段二：递归返回 (出栈 / Pop) 】
最底层的 Test1(2) 结束后，栈顶函数帧被销毁（出栈），控制权依次交还给下方函数。

   此时栈结构           出栈 1 次            出栈 2 次             出栈 3 次(结束)
| 3. Test1(2)    |
+----------------+   |                |
| 2. Test1(3)    |   | 2. Test1(3)    |    |                |
+----------------+ ->+----------------+ -> |                | ->  |                |
| 1. Test1(4)    |   | 1. Test1(4)    |    | 1. Test1(4)    |     |                |
+----------------+   +----------------+    +----------------+     +----------------+
 执行:打印 n = 2          恢复第二层执行          恢复第一层执行           全部执行完毕
 然后结束，出栈销毁        打印当前层的 n=2        打印当前层的 n=3         主函数继续执行
                       然后结束，出栈销毁        然后结束，出栈销毁


最终控制台输出：
n = 2   (来自第3层 Test1(2))
n = 2   (来自第2层 Test1(3)，它自己的n由于之前执行了n--，所以也是2)
n = 3   (来自第1层 Test1(4)，它自己的n由于之前执行了n--，所以是3)
*/

// Test3 求斐波那契数列的第n个数,这是一个简答且经典的递归问题，记得复习
func Test3(n int) int {
	if n == 1 || n == 2 {
		return 1
	}
	return Test3(n-1) + Test3(n-2) // else 是多余的，直接放这就行
}

// Test4 已知 f1 = 3; fn = 2*f(n-1) + 1
func Test4(n int) int {
	if n == 1 {
		return 3
	}
	return 2*Test4(n-1) + 1
}

// 其实递归主要就是写出他的递归表达式，然后执行就行，猴子吃桃和斐波那契都是经典问题

// Test5 猴子吃桃问题: 每天吃一半加一个，第十天只剩一个了
func Test5(n int) int {
	if n == 1 {
		return 1 // 这个是假设桃子增加
	}
	return 2 * (Test5(n-1) + 1) // 注意这个公式，可以说整体就靠这个公式，注意是加1再乘2
}

// MonkeyPeach 更直观的经典写法，n 代表“第几天”
func MonkeyPeach(day int) int {
	if day == 10 {
		return 1 // 这个终止条件是要给前面的天数去计算的，会影响最终结果
		// 这个是正经桃子减少
	}
	// 第 day 天的桃子数 = (第 day+1 天的桃子数 + 1) * 2
	return (MonkeyPeach(day+1) + 1) * 2 // 而且我们做的乘法不用担心像除法不是整数的问题
}

// 在给函数传参时，因为函数内部指明了要接收的数据类型，我们只传值时，编译器为了不损失精度会自动转为函数需要的数据类型。
// sum(1,2)作为输入，编译器会把这里的1，2转为float
func sum(n1, n2 float32) float32 {
	fmt.Printf("n1 的类型是 %T:", n1)
	return n1 + n2
}

